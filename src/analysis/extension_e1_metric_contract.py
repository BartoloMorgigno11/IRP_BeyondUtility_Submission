def write_csv(path: Path, rows: Sequence[Mapping[str, str]], fieldnames: Sequence[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def read_csv_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def split_tokens(value: str) -> list[str]:
    return [token for token in value.split(";") if token]


def validate_rows() -> None:
    metric_ids = set()
    for row in METRIC_ROWS:
        metric_id = row["metric_id"]
        if metric_id in metric_ids:
            raise ValueError(f"duplicate metric_id: {metric_id}")
        metric_ids.add(metric_id)
        task = row["task_applicability"]
        if task not in TASK_VALUES:
            raise ValueError(f"{metric_id} has invalid task {task}")
        if row["recommender_applicability"] not in RECOMMENDER_VALUES:
            raise ValueError(f"{metric_id} has invalid recommender applicability")
        provenance = set(split_tokens(row["provenance_classification"]))
        if not provenance or not provenance.issubset(PROVENANCE_CLASSES):
            raise ValueError(f"{metric_id} has invalid provenance {provenance}")
        req_class = row["fifth_dataset_requirement_classification"]
        if req_class not in REQUIREMENT_CLASSES:
            raise ValueError(f"{metric_id} has invalid requirement class {req_class}")
        flags = set(split_tokens(row["new_inference_requirement"]))
        if not flags or not flags.issubset(INFERENCE_FLAGS):
            raise ValueError(f"{metric_id} has invalid inference flags {flags}")
        if row["family"] == "local_extension" and "PAPER_SPECIFIED" in provenance:
            raise ValueError(f"local extension mislabeled as paper metric: {metric_id}")
        if row["family"] != "local_extension" and row["implementation_status"] == "MISSING":
            # Missing paper components are allowed, but only with clear evidence.
            if "NOT_IMPLEMENTED" not in provenance:
                raise ValueError(f"missing row lacks NOT_IMPLEMENTED provenance: {metric_id}")

    coverage_ids = {row["metric_or_analysis_id"] for row in COVERAGE_ROWS}
    required_coverage_ids = {
        "hr_at_5",
        "ndcg_at_5",
        "self_information_at_5",
        "serendipity_at_5",
        "arp_at_5",
        "aplt_at_5",
        "popreo_at_5",
        "item_coverage_at_5",
        "oic_at_5",
        "shannon_entropy_at_5",
        "gini_at_5",
        "dpd_at_5",
        "jain_index_at_5",
        "hallucination_rate_at_5",
    }
    missing_coverage = required_coverage_ids.difference(coverage_ids)
    if missing_coverage:
        raise ValueError(f"coverage table missing rows: {sorted(missing_coverage)}")
    for row in COVERAGE_ROWS:
        for dataset in ["beauty", "sports", "ml_1m", "lastfm"]:
            if row[dataset] not in COVERAGE_VALUES:
                raise ValueError(f"{row['metric_or_analysis_id']} has invalid coverage status")

    for row in REQUIREMENT_ROWS:
        if not row["needed_by_metric_analysis"]:
            raise ValueError(f"requirement lacks metric pointer: {row['requirement']}")
        if row["requirement_class"] not in REQUIREMENT_CLASSES:
            raise ValueError(f"invalid requirement class: {row['requirement']}")

    for row in INFERENCE_ROWS:
        flags = set(split_tokens(row["inference_requirement"]))
        if not flags or not flags.issubset(INFERENCE_FLAGS):
            raise ValueError(f"invalid inference row flags: {row['analysis_id']}")


def md_escape(value: object) -> str:
    text = str(value)
    return text.replace("|", "\\|").replace("\n", " ")


def markdown_table(rows: Sequence[Mapping[str, str]], columns: Sequence[str], *, limit: int | None = None) -> list[str]:
    selected = list(rows if limit is None else rows[:limit])
    lines = [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join(["---"] * len(columns)) + " |",
    ]
    for row in selected:
        lines.append("| " + " | ".join(md_escape(row.get(column, "")) for column in columns) + " |")
    return lines


